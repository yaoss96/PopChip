#!/usr/bin/env python3
"""Derive the large-scale table's CPU+GPU+NoC power envelope.

The synchronized LEGOSim archive contains measured PopNet/ORION NoC average
power, but its GPGPU-Sim workers run with power simulation disabled and the
bare-metal router is not a Sniper/McPAT workload.  Consequently this script
does *not* claim a synchronized run-time average.  It combines the independently
audited chiplet-library peak-power sum with each run's ORION average:

    P_env = P_chiplet,pk (CPU + all GPUs) + P_NoC,ORION,avg.

The result is a reproducible provisioned-power envelope suitable for checking
the paper's peak-power budgeting model.  It must not be relabeled as measured
package or wall-plug power.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


METHOD_ORDER = ("ilp", "floorplet", "tap")
SCALE_TO_MESH = {8: 6, 16: 8, 32: 12, 64: 12, 128: 16}


def load_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def audit_path(proxy_root: Path, experts: int, mesh: int) -> Path:
    return proxy_root / "audits" / f"e{experts:03d}_m{mesh:02d}_proxy_audit.json"


def fmt_cycles(value: int) -> str:
    return f"{value:,}".replace(",", "{,}")


def fmt_decimal(value: str) -> str:
    whole, fraction = value.split(".")
    grouped = f"{int(whole):,}".replace(",", "{,}")
    return f"{grouped}.{fraction}"


def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    default_replay = (
        repo_root
        / "out"
        / "scaling_legosim_final_twostage_20260801"
        / "table3_legosim_real.json"
    )
    default_proxy = repo_root / "out" / "scaling_secondary_proxy_experiment_20260801"
    default_csv = default_replay.with_name("table3_power_envelope.csv")
    default_tex = default_replay.with_name("table3_power_envelope.tex")

    parser = argparse.ArgumentParser()
    parser.add_argument("--replay-audit", type=Path, default=default_replay)
    parser.add_argument("--proxy-audit-root", type=Path, default=default_proxy)
    parser.add_argument("--output-csv", type=Path, default=default_csv)
    parser.add_argument("--output-tex", type=Path, default=default_tex)
    args = parser.parse_args()

    replay = load_json(args.replay_audit)
    raw_rows = replay.get("audit_rows", [])
    if len(raw_rows) != 15:
        raise ValueError(f"Expected 15 audited replay rows, found {len(raw_rows)}")

    indexed: dict[tuple[int, str], dict] = {}
    for row in raw_rows:
        if row.get("audit_status") != "PASS":
            raise ValueError(f"Replay audit is not PASS: {row.get('case_id')} {row.get('method')}")
        key = (int(row["experts"]), str(row["method"]))
        if key in indexed:
            raise ValueError(f"Duplicate replay row: {key}")
        indexed[key] = row

    output_rows: list[dict[str, object]] = []
    tex_lines = [
        "% Generated by src/derive_scaling_power_envelope.py.",
        "% P_env = audited CPU+GPU chiplet-library peak sum + measured ORION NoC average.",
    ]
    for experts, mesh in SCALE_TO_MESH.items():
        proxy = load_json(audit_path(args.proxy_audit_root, experts, mesh))
        if proxy.get("pass") is not True:
            raise ValueError(f"Proxy audit is not PASS for E{experts}")

        source = proxy["source_ilp"]
        source_validation = source["validation"]
        chiplet_peak = float(source_validation["independent_peak_power_sum_W"])
        bom = source["BOM"]
        gpu_l = int(bom["GPU-L"])
        gpu_s = int(bom["GPU-S"])
        if int(bom["CPU"]) != 1:
            raise ValueError(f"Expected one CPU at E{experts}")

        for candidate in proxy["proxies"]:
            candidate_peak = float(candidate["validation"]["independent_peak_power_sum_W"])
            if candidate_peak != chiplet_peak:
                raise ValueError(f"Peak-power mismatch at E{experts}")

        per_method: dict[str, dict[str, object]] = {}
        for method in METHOD_ORDER:
            row = indexed[(experts, method)]
            if row["mesh"] != f"{mesh}x{mesh}":
                raise ValueError(f"Mesh mismatch at E{experts} {method}")
            if int(row["gpu_l_count"]) != gpu_l or int(row["gpu_s_count"]) != gpu_s:
                raise ValueError(f"BOM mismatch at E{experts} {method}")
            noc = float(row["orion_noc_power_W"])
            envelope = chiplet_peak + noc
            record = {
                "experts": experts,
                "mesh": f"{mesh}x{mesh}",
                "gpu_L_S": f"{gpu_l}/{gpu_s}",
                "method": method,
                "cycles": int(row["legosim_cycles"]),
                "chiplet_peak_power_W": f"{chiplet_peak:.3f}",
                "noc_orion_average_W": f"{noc:.6f}",
                "provisioned_power_envelope_W": f"{envelope:.3f}",
                "replay_audit_status": row["audit_status"],
                "proxy_audit_status": "PASS",
            }
            output_rows.append(record)
            per_method[method] = record

        cells: list[str] = [str(experts), f"${mesh}\\times{mesh}$", f"{gpu_l}/{gpu_s}"]
        for method in METHOD_ORDER:
            record = per_method[method]
            cells.extend(
                [
                    fmt_cycles(int(record["cycles"])),
                    fmt_decimal(str(record["provisioned_power_envelope_W"])),
                ]
            )
        tex_lines.append(" & ".join(cells) + r" \\")

    args.output_csv.parent.mkdir(parents=True, exist_ok=True)
    with args.output_csv.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(output_rows[0]))
        writer.writeheader()
        writer.writerows(output_rows)
    args.output_tex.write_text("\n".join(tex_lines) + "\n", encoding="utf-8")

    print(f"wrote {args.output_csv}")
    print(f"wrote {args.output_tex}")
    for row in output_rows:
        print(
            "E{experts:<3d} {method:<10s} cycles={cycles:<8d} "
            "P_chiplet,pk={chiplet_peak_power_W} W P_NoC={noc_orion_average_W} W "
            "P_env={provisioned_power_envelope_W} W".format(**row)
        )


if __name__ == "__main__":
    main()
