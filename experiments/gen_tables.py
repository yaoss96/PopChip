# -*- coding: utf-8 -*-
"""Table II and Fig. 5 data from results/legosim/measured.csv.

Writes results/paper/main-results-data.tex and results/paper/ablation-data.tex.
"""
from __future__ import print_function
import io
import os
import statistics
import ispa_common as C

BS = chr(92)  # backslash, kept out of string literals on purpose
ROWS = [("e008_m06", "8", "6"), ("e016_m08", "16", "8"), ("e032_m12", "32", "12"),
        ("e064_m12", "64", "12"), ("e064_m16", "64", "16"), ("e128_m16", "128", "16")]
KEY = {"e008_m06": "8", "e016_m08": "16", "e032_m12": "32", "e064_m12": "64a",
       "e064_m16": "64b", "e128_m16": "128"}


def macro(name, body):
    return BS + "renewcommand{" + BS + name + "}{" + body + "}"


def main():
    M = {(r["case"], r["method"]): r["measured_cycles"] for r in C.read_measured()}
    lines = []
    abl = {"blind": [], "rank": [], "tap": [], "fp": [], "joint": []}
    summary = {}
    for cid, E, X in ROWS:
        sol = C.read_json(C.case_paths(cid)["popchip"])
        c = C.counts(sol)
        pc = M[(cid, "popchip")]
        blind = int(statistics.median([M[(cid, "blind%d" % s)] for s in (1, 2, 3)]))
        fp, tap = M[(cid, "floorplet")], M[(cid, "tap")]
        rank = M.get((cid, "poprank-greedy"))
        best = min(v for v in (pc, rank, fp, tap, blind) if v)

        def cell(v):
            if v is None:
                return "--"
            t = "%.3f" % (v / 1000.0)
            return BS + "textbf{" + t + "}" if v == best else t

        gap = sol.get("mip_gap")
        gtxt = "%.1f" % (100 * gap) if gap is not None else "--"
        row = [E, "$" + X + "{" + BS + "times}" + X + "$",
               "%d/%d" % (c.get("GPU-L", 0), c.get("GPU-S", 0)),
               "%.2f" % sol["time_to_first_feasible_s"], gtxt,
               cell(pc), cell(rank), cell(fp), cell(tap), cell(blind)]
        lines.append(" & ".join(row) + " " + BS + BS)
        k = KEY[cid]
        abl["blind"].append("(%s,%.4f) [+%.1f]" % (k, blind / float(pc), 100 * (blind / float(pc) - 1)))
        if rank:
            abl["rank"].append("(%s,%.4f)" % (k, rank / float(pc)))
        abl["tap"].append("(%s,%.4f)" % (k, tap / float(pc)))
        abl["fp"].append("(%s,%.4f)" % (k, fp / float(pc)))
        abl["joint"].append("(%s,1.0000)" % k)
        summary[cid] = {"popchip": pc, "poprank_g": rank, "fp": fp, "tap": tap, "blind_med": blind,
                        "red_vs_blind_pct": 100 * (1 - pc / float(blind)),
                        "red_vs_fp_pct": 100 * (1 - pc / float(fp)),
                        "red_vs_tap_pct": 100 * (1 - pc / float(tap)),
                        "rank_over_pc_pct": (100 * (rank / float(pc) - 1)) if rank else None}
    out = os.path.join(C.RESULTS, "paper")
    if not os.path.isdir(out):
        os.makedirs(out)
    hdr = ["% Generated by experiments/gen_tables.py from results/legosim/measured.csv",
           "% Experts & Mesh & L/S & t_ff(s) & gap(%) & PopChip & PopRank-G & FP-px & TAP-px & Blind (k cycles)",
           "% Blind = median of three random expert-to-die permutations at PopChip's anchors."]
    with io.open(os.path.join(out, "main-results-data.tex"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(hdr + lines + [BS + "bottomrule"]) + "\n")
    abl_lines = ["% Generated by experiments/gen_tables.py: measured cycles / PopChip.",
                 macro("AblBlindCoords", " ".join(abl["blind"])),
                 macro("AblRankCoords", " ".join(abl["rank"])),
                 macro("AblTapCoords", " ".join(abl["tap"])),
                 macro("AblFpCoords", " ".join(abl["fp"])),
                 macro("AblJointCoords", " ".join(abl["joint"])),
                 BS + "AblationReadytrue"]
    with io.open(os.path.join(out, "ablation-data.tex"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(abl_lines) + "\n")
    C.write_json(os.path.join(C.RESULTS, "table3_summary.json"), summary)
    for k in sorted(summary):
        v = summary[k]
        print(k, {kk: (round(vv, 2) if isinstance(vv, float) else vv) for kk, vv in v.items()})


if __name__ == "__main__":
    main()
