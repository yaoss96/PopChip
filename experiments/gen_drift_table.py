# -*- coding: utf-8 -*-
"""Write paper_date/drift-table.tex from results/drift/*.json (+ real-trace drift)."""
from __future__ import print_function
import glob, io, json, os
import ispa_common as C

BS = chr(92)
CLASSES = [("Skew $" + BS + "alpha" + BS + "in" + BS + "{0.3,1,1.2" + BS + "}$", ("a0.3", "a1.0", "a1.2")),
           ("Adjacent swaps ($" + BS + "times$3)", ("mild_s1", "mild_s2", "mild_s3")),
           ("Re-ranking ($" + BS + "times$3)", ("shuffle_s1", "shuffle_s2", "shuffle_s3"))]
POL = ("static", "remap_rank", "remap_ls", "redesign")


def overheads(rec):
    red = rec["redesign"].get("T")
    vals = {"static": rec["static"], "remap_rank": rec["remap_rank"],
            "remap_ls": rec["remap_ls"], "redesign": red}
    best = min(v for v in vals.values() if v)
    return {k: (100.0 * (v / best - 1.0) if v else None) for k, v in vals.items()}


res = {}
for f in sorted(glob.glob(os.path.join(C.RESULTS, "drift", "e*.json"))):
    r = C.read_json(f)
    res[r["case"]] = r
rows = []
summary = {}
for label, keys in CLASSES:
    worst = {p: 0.0 for p in POL}
    n = 0
    for cid, r in res.items():
        for k in keys:
            if k in r["drift"]:
                o = overheads(r["drift"][k])
                n += 1
                for p in POL:
                    if o[p] is not None:
                        worst[p] = max(worst[p], o[p])
    summary[label] = {"n": n, "worst": worst}
    rows.append(label + " & " + " & ".join("%.1f" % worst[p] for p in POL) + " " + BS + BS)
real = os.path.join(C.RESULTS, "realtrace_drift.json")
if os.path.exists(real):
    rr = C.read_json(real)
    missing = set(rr.get("redesign_missing", []))
    for label, rec in rr.get("rows", []):
        cells = ["--" if (p == "redesign" and label in missing) else "%.1f" % rec[p] for p in POL]
        rows.append(label + " & " + " & ".join(cells) + " " + BS + BS)
cases = sorted(res)
cap = ("Drift on fixed hardware: worst case above the best design found "
       "(" + BS + "%, analytical $T$).")
tex = [BS + "begin{table}[t]",
       BS + "caption{" + cap + "}",
       BS + "label{tab:drift}",
       BS + "centering" + BS + "small",
       BS + "setlength{" + BS + "tabcolsep}{3.4pt}",
       BS + "begin{tabular}{lcccc}",
       BS + "toprule",
       "Drift & Static & Rank & Rank+LS & Redesign " + BS + BS,
       BS + "midrule"] + rows + [BS + "bottomrule", BS + "end{tabular}", BS + "end{table}"]
with io.open(os.path.join(C.RESULTS, "paper", "drift-table.tex"), "w", encoding="utf-8") as fh:
    fh.write("% AUTO-GENERATED by gen_drift_table.py\n" + "\n".join(tex) + "\n")
print(json.dumps(summary, indent=1))
