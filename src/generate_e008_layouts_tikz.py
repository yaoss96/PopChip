# -*- coding: utf-8 -*-
"""Emit prior-layouts-tikz.tex for the e008 SCALING case (1 GPU-L / 8 GPU-S on a
6x6 Mesh), single-column format, from the ILP/Floorplet/TAP solution JSONs.
Coordinate mapping: source (l,i,j) -> TikZ (x,y)=(j, 6-i-height).
"""
from __future__ import print_function
import json, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = ROOT + "/out/joint_bom_scaling_fresh_20260802"
OUT = ROOT + "/paper_date/prior-layouts-tikz.tex"
ABBR = {"t_attn": "At", "t_combine": "Cb", "t_dispatch": "Ds",
        "t_gate": "Gt", "t_norm": "Nm"}
EXP = re.compile(r"^e\((\d+)\)$")
PANELS = [
    ("ilp-perf", B + "/solutions/scaling/e008_m06/ilp_perf.json",
     r"(a) ILP-Perf: 110{,}425"),
    ("floorplet", B + "/baselines/scaling/e008_m06/prior/floorplet.json",
     r"(b) Floorplet~\cite{floorplet}: 111{,}744"),
    ("tap", B + "/baselines/scaling/e008_m06/prior/tap.json",
     r"(c) TAP-2.5D~\cite{tap25d}: 113{,}013"),
]

PRE = r"""%% Auto-generated by generate_e008_layouts_tikz.py; do not edit.
%% e008 scaling case: 1 GPU-L / 8 GPU-S / 1 CPU on a 6x6 Mesh.
%% Coordinates: source (l,i,j) maps to TikZ (x,y)=(j,6-i-height).
%% At/Gt/Ds/Cb/Nm = attention/gate/dispatch/combine/norm.
\centering
\begingroup
\tikzset{
  priorgrid/.style={draw=black!28,line width=0.25pt},
  priorlarge/.style={draw=blue!65!black,fill=morandiA!62,line width=0.55pt},
  priorsmall/.style={draw=green!45!black,fill=morandiC!62,line width=0.55pt},
  priorcpu/.style={draw=orange!65!black,fill=morandiD!78,line width=0.55pt},
  priorlabel/.style={font=\sffamily\tiny,inner sep=0.3pt,align=center}
}
\newcommand{\priormesh}{%
  \draw[priorgrid,step=1] (0,0) grid (6,6);
  \draw[black!65,line width=0.45pt] (0,0) rectangle (6,6);
}
\newcommand{\priorsgpu}[3]{%
  \filldraw[priorsmall] (#1,#2) rectangle ++(1,1);
  \node[priorlabel] at (#1+0.5,#2+0.5) {#3};
}
\newcommand{\priorlgpu}[3]{%
  \filldraw[priorlarge] (#1,#2) rectangle ++(2,2);
  \node[priorlabel] at (#1+1,#2+1) {#3};
}
\newcommand{\priorcpuchip}[3]{%
  \filldraw[priorcpu] (#1,#2) rectangle ++(1,1);
  \node[priorlabel] at (#1+0.5,#2+0.5) {#3};
}
"""


def label(site):
    experts = [EXP.match(t).group(1) for t in site.get("tasks", []) if EXP.match(t)]
    controls = [ABBR[t] for t in site.get("tasks", []) if t in ABBR]
    if site["type"] == "CPU":
        base = "C"
    else:
        pre = "L" if site["type"] == "GPU-L" else "S"
        base = "%s:e%s" % (pre, experts[0]) if experts else pre
    if controls:
        base += r"\\" + "+".join(controls)
    return base


def draw(site):
    i, j = int(site["i"]), int(site["j"])
    x = j
    if site["type"] == "GPU-L":
        y = 6 - i - 2
        return r"  \priorlgpu{%d}{%d}{%s}" % (x, y, label(site))
    y = 6 - i - 1
    cmd = "priorcpuchip" if site["type"] == "CPU" else "priorsgpu"
    return r"  \%s{%d}{%d}{%s}" % (cmd, x, y, label(site))


def panel(path, caption):
    sol = json.load(open(path))
    lines = [r"\begin{minipage}{0.32\columnwidth}", r"\centering",
             r"\begin{tikzpicture}[x=0.40cm,y=0.40cm]", r"  \priormesh"]
    for s in sorted(sol["sites"], key=lambda s: (s["i"], s["j"])):
        lines.append(draw(s))
    lines += [r"\end{tikzpicture}\\[-0.5mm]",
              r"\scriptsize " + caption, r"\end{minipage}"]
    return "\n".join(lines)


def main():
    body = PRE
    panels = [panel(p, cap) for _, p, cap in PANELS]
    body += "\n\\hfill\n".join(panels) + "\n\\endgroup\n"
    with open(OUT, "w") as fh:
        fh.write(body)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
